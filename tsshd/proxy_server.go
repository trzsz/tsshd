func startServerProxy(args *tsshdArgs, info *ServerInfo, conn frontendConnection) (*serverProxy, error) {
	proxyKey := make([]byte, 32)
	if _, err := crypto_rand.Read(proxyKey); err != nil {
		return nil, fmt.Errorf("rand proxy key failed: %v", err)
	}
	info.ProxyKey = fmt.Sprintf("%x", proxyKey)
	cipherBlock, err := aes.NewCipher(proxyKey)
	if err != nil {
		return nil, fmt.Errorf("aes new cipher failed: %v", err)
	}

	proxy := &serverProxy{
		args:         args,
		frontendConn: conn,
		cipherBlock:  &cipherBlock,
	}

	// Publish the keys before either the frontend or KCP starts reading packets.
	if args.KCP {
		proxy.kcpCrypto, err = newKcpServerCrypto(info, args.Attachable)
		if err != nil {
			return nil, err
		}
	}

	if !args.Attachable || args.Socket {
		if info.ClientID == 0 {
			info.ClientID, err = randomProxyID(0)
			if err != nil {
				return nil, fmt.Errorf("rand client id failed: %v", err)
			}
		}
		proxy.clientID = info.ClientID
	}

	if !args.Attachable {
		client, err := proxy.newClientState(info.ClientID)
		if err != nil {
			return nil, fmt.Errorf("new client state failed: %v", err)
		}
		proxy.soleClient = client

		if args.KCP {
			// The KCP listener opens the packets of the sole client itself. Only
			// those it accepts show that the client is alive: a packet replayed
			// to a server speaking protocol version 3 does not.
			proxy.kcpCrypto.onPacketAccepted = func() { proxy.updateClientChecker(client) }
		}
	}

	info.ServerID, err = randomProxyID(info.ClientID)
	if err != nil {
		return nil, fmt.Errorf("rand server id failed: %v", err)
	}
	proxy.serverID = info.ServerID

	if args.TCP {
		info.ProxyMode = kProxyModeTCP
	}

	conn.start(proxy)

	return proxy, nil
}
