var errClientDisconnected = errors.New("client disconnected")

type proxyClientAddr struct {
	clientID uint64
}

func (a *proxyClientAddr) Network() string {
	return "udp"
}

func (a *proxyClientAddr) String() string {
	return strconv.FormatUint(a.clientID, 16)
}

// The client nonce is generated by the client and is fresh for each client.
const kClientNonceSize = 16

// clientHello is what a client announces about itself when authenticating.
// Clients older than protocol version 3 do not announce anything.
type clientHello struct {
	protoVersion int
	clientNonce  []byte
}

// pathKey identifies a client path. local is the server address the client sent to.
type pathKey struct {
	remote netip.AddrPort
	local  netip.Addr
}

// udpPath is the socket, remote and local address a client authenticated on.
type udpPath struct {
	socket udpSocket
	key    pathKey
	oob    []byte // set when the path is accepted
}

func (p *udpPath) send(buf []byte) error {
	return p.socket.writeTo(buf, p.key.remote, p.oob)
}

type clientState struct {
	sealed       atomic.Bool
	closed       atomic.Bool
	server       atomic.Pointer[sshUdpServer]
	proxyAddr    proxyClientAddr
	serialNumber atomic.Uint64
	clientConn   atomic.Pointer[net.TCPConn]
	clientPath   atomic.Pointer[udpPath]
	authedPath   atomic.Pointer[udpPath]
	frontendConn frontendConnection
	clientMutex  sync.Mutex
	clientCond   *sync.Cond
	kcpCrypto    atomic.Pointer[rotatingCrypto]
	udpTraffic   atomic.Pointer[trafficStats]
	helloMutex   sync.Mutex
	hello        *clientHello
	tcpAuthMutex sync.Mutex
}

func (c *clientState) remoteAddr() string {
	if path := c.clientPath.Load(); path != nil {
		return path.key.remote.String()
	}
	if conn := c.clientConn.Load(); conn != nil {
		return conn.RemoteAddr().String()
	}
	return c.proxyAddr.String()
}

func (c *clientState) waitClientConn() *net.TCPConn {
	if conn := c.clientConn.Load(); conn != nil {
		return conn
	}

	c.clientMutex.Lock()
	defer c.clientMutex.Unlock()

	conn := c.clientConn.Load()
	for conn == nil {
		if c.clientCond == nil {
			return nil
		}
		c.clientCond.Wait()
		conn = c.clientConn.Load()
	}

	return conn
}

func (c *clientState) setClientConn(oldConn, newConn *net.TCPConn) bool {
	c.clientMutex.Lock()

	closed := c.closed.Load()
	if closed {
		newConn = nil
	}

	if oldConn == nil {
		oldConn = c.clientConn.Swap(newConn)
	} else {
		if !c.clientConn.CompareAndSwap(oldConn, newConn) {
			oldConn = nil
		}
	}
	if c.clientCond != nil {
		c.clientCond.Broadcast()
	}
	c.clientMutex.Unlock()

	if oldConn != nil {
		_ = oldConn.Close()
	}

	return !closed
}

func (c *clientState) setClientPath(oldPath, newPath *udpPath) bool {
	c.clientMutex.Lock()
	defer c.clientMutex.Unlock()

	closed := c.closed.Load()
	if closed {
		newPath = nil
	}

	if oldPath == nil {
		oldPath = c.clientPath.Swap(newPath)
	} else {
		if !c.clientPath.CompareAndSwap(oldPath, newPath) {
			oldPath = nil
		}
	}

	if oldPath != nil {
		c.frontendConn.delClientMap(c, oldPath)
	}

	if newPath != nil {
		c.frontendConn.addClientMap(c)
	}

	return !closed
}

func (c *clientState) setAuthedPath(oldPath, newPath *udpPath) bool {
	c.clientMutex.Lock()
	defer c.clientMutex.Unlock()

	closed := c.closed.Load()
	if closed {
		newPath = nil
	}

	if oldPath == nil {
		oldPath = c.authedPath.Swap(newPath)
	} else {
		if !c.authedPath.CompareAndSwap(oldPath, newPath) {
			oldPath = nil
		}
	}

	if oldPath != nil {
		c.frontendConn.delAuthedMap(c, oldPath)
	}

	if newPath != nil {
		c.frontendConn.addAuthedMap(c)
	}

	return !closed
}

func (c *clientState) Close() {
	c.clientMutex.Lock()

	if !c.closed.CompareAndSwap(false, true) {
		c.clientMutex.Unlock()
		return
	}

	if c.clientCond != nil {
		c.clientCond.Broadcast()
		c.clientCond = nil
	}

	c.clientMutex.Unlock()

	// clientState instances are retained to prevent replay attacks,
	// so release references that are no longer needed.

	c.server.Store(nil)
	c.kcpCrypto.Store(nil)
	c.setClientConn(nil, nil)
	c.setClientPath(nil, nil)
	c.setAuthedPath(nil, nil)
	c.udpTraffic.Store(nil)
}

type frontendConnection interface {
	start(*serverProxy)
	readFrom([]byte) (int, *clientState)
	writeTo([]byte, *clientState) error
	addClientMap(*clientState)
	delClientMap(*clientState, *udpPath)
	addAuthedMap(*clientState)
	delAuthedMap(*clientState, *udpPath)
	Close()
}

// udpPacket hands a packet from a socket reader to readFrom.
type udpPacket struct {
	buf  []byte // valid until done is signaled
	path udpPath
	done chan struct{}
}

type udpFrontendConn struct {
	proxy       *serverProxy
	sockets     []udpSocket
	packetCh    chan udpPacket
	closed      chan struct{} // closed after all readLoops return
	cacheClient atomic.Pointer[clientState]
	clientMutex sync.Mutex
	clientMap   map[pathKey]*clientState
	authedMutex sync.Mutex
	authedMap   map[pathKey]*clientState
}

func (c *udpFrontendConn) start(proxy *serverProxy) {
	c.proxy = proxy
	c.packetCh = make(chan udpPacket)
	c.closed = make(chan struct{})

	// Sockets stay open until exit, so clients can reconnect at any time.
	var readers sync.WaitGroup
	for _, socket := range c.sockets {
		addOnExitFunc(func() { _ = socket.Close() })
		readers.Go(func() { c.readLoop(socket) })
	}
	go func() {
		readers.Wait()
		close(c.closed)
	}()
}

func (c *udpFrontendConn) readLoop(socket udpSocket) {
	buf := make([]byte, 0xffff)
	done := make(chan struct{})
	for {
		n, remote, local, err := socket.readFrom(buf)
		if err != nil {
			if errors.Is(err, net.ErrClosed) {
				return
			}
			warning("frontend read udp failed: %v", err)
			time.Sleep(10 * time.Millisecond)
			continue
		}

		c.packetCh <- udpPacket{buf[:n], udpPath{socket: socket, key: pathKey{remote, local}}, done}
		<-done
	}
}

func (c *udpFrontendConn) addClientMap(client *clientState) {
	if !c.proxy.args.Attachable {
		return
	}

	path := client.clientPath.Load()
	if path == nil {
		return
	}

	c.clientMutex.Lock()
	if c.clientMap == nil {
		c.clientMap = make(map[pathKey]*clientState)
	}
	c.clientMap[path.key] = client
	c.clientMutex.Unlock()
}

func (c *udpFrontendConn) delClientMap(client *clientState, path *udpPath) {
	if !c.proxy.args.Attachable {
		return
	}

	if path == nil {
		return
	}

	c.clientMutex.Lock()
	if c.clientMap[path.key] == client {
		delete(c.clientMap, path.key)
	}
	c.clientMutex.Unlock()
}

func (c *udpFrontendConn) addAuthedMap(authed *clientState) {
	if !c.proxy.args.Attachable {
		return
	}

	path := authed.authedPath.Load()
	if path == nil {
		return
	}

	c.authedMutex.Lock()
	if c.authedMap == nil {
		c.authedMap = make(map[pathKey]*clientState)
	}
	c.authedMap[path.key] = authed
	c.authedMutex.Unlock()
}

func (c *udpFrontendConn) delAuthedMap(client *clientState, path *udpPath) {
	if !c.proxy.args.Attachable {
		return
	}

	if path == nil {
		return
	}

	c.authedMutex.Lock()
	if c.authedMap[path.key] == client {
		delete(c.authedMap, path.key)
	}
	c.authedMutex.Unlock()
}

func (c *udpFrontendConn) Close() {
	for _, socket := range c.sockets {
		_ = socket.Close()
	}
}

func isSamePath(path *udpPath, key pathKey) bool {
	return path != nil && path.key == key
}

func (c *udpFrontendConn) getClient(key pathKey) (*clientState, bool, bool) {
	if !c.proxy.args.Attachable {
		client := c.proxy.soleClient
		if isSamePath(client.clientPath.Load(), key) {
			return client, true, false
		}
		if isSamePath(client.authedPath.Load(), key) {
			return client, false, true
		}
		return nil, false, false
	}

	if client := c.cacheClient.Load(); client != nil {
		if isSamePath(client.clientPath.Load(), key) {
			return client, true, false
		}
		if isSamePath(client.authedPath.Load(), key) {
			return client, false, true
		}
	}

	c.clientMutex.Lock()
	client := c.clientMap[key]
	c.clientMutex.Unlock()

	if client != nil && isSamePath(client.clientPath.Load(), key) {
		c.cacheClient.Store(client)
		return client, true, false
	}

	c.authedMutex.Lock()
	authed := c.authedMap[key]
	c.authedMutex.Unlock()

	if authed != nil && isSamePath(authed.authedPath.Load(), key) {
		return authed, false, true
	}

	return nil, false, false
}

// readFrom processes incoming UDP packets and client authentication.
// Calls must be serialized; serverProxy.ReadFrom ensures this with readMutex.
// It returns a nil client once all sockets are closed.
func (c *udpFrontendConn) readFrom(buf []byte) (int, *clientState) {
	for {
		var packet udpPacket
		select {
		case packet = <-c.packetCh:
		case <-c.closed:
			return 0, nil
		}
		n := copy(buf, packet.buf)
		packet.done <- struct{}{}
		key := packet.path.key

		client, isClientPath, isAuthedPath := c.getClient(key)

		// Case 1: packet from current effective client.
		// Fast path — directly forward.
		if isClientPath {
			if n <= kSafeToDropPacketLen {
				continue
			}
			return n, client
		}

		// Case 2: packet from authenticated but not yet activated client.
		if isAuthedPath {

			// Check whether this is still an authentication packet.
			isAuthPacket, clientID, newSerialNumber, hello := c.proxy.openAuthPacket(buf[:n])

			path := client.authedPath.Load()
			if path == nil {
				warning("authed path missing: client_id=%x, remote=%s", client.proxyAddr.clientID, key.remote)
				continue
			}

			// First non-auth packet means handshake phase completed.
			// Promote authedPath to effective client.
			if !isAuthPacket {
				if !client.setClientPath(nil, path) {
					debug("set client path failed: client [%x] is closed", client.proxyAddr.clientID)
					continue
				}
				if !client.setAuthedPath(nil, nil) {
					debug("skip clearing authed path: client [%x] is closed", client.proxyAddr.clientID)
					continue
				}
				c.proxy.onNewClientConn(client)
				if n <= kSafeToDropPacketLen {
					continue
				}
				return n, client
			}

			// With pre-v3 protocols, the server's authentication response may be
			// reflected back and mistaken for a client authentication packet. In
			// attachable mode, the server ID in that response may be interpreted as
			// a new client ID. Normal clients never send such packets.
			if clientID != client.proxyAddr.clientID {
				warning("unexpected auth packet on authed path: expected_client_id=%x, received_client_id=%x, remote=%s",
					client.proxyAddr.clientID, clientID, key.remote)
				client.setAuthedPath(nil, nil)
				continue
			}

			// Redundant authentication packet.
			// Accept the current or a newer serial number and resend the auth response.
			oldSerialNumber := client.serialNumber.Load()
			if newSerialNumber < oldSerialNumber {
				// The client serial number only increases. Retransmissions on the current
				// authenticated path may carry the current serial, but never an older one.
				// Packets from an old path must not arrive on this path.
				warning("stale auth packet on authed path: client_id=%x, current_serial=%d, received_serial=%d, remote=%s",
					client.proxyAddr.clientID, oldSerialNumber, newSerialNumber, key.remote)
				continue
			}

			if !c.proxy.acceptClientHello(client, hello) {
				continue
			}

			if !client.serialNumber.CompareAndSwap(oldSerialNumber, newSerialNumber) {
				// Calls to readFrom are serialized, so the serial number should not change between the load and CAS.
				warning("unexpected serial change on authed path: client_id=%x, expected_serial=%d, received_serial=%d, current_serial=%d, remote=%s",
					client.proxyAddr.clientID, oldSerialNumber, newSerialNumber, client.serialNumber.Load(), key.remote)
				continue
			}

			// Reply on the authenticated path.
			b, err := c.proxy.sealAuthPacket(newSerialNumber, hello)
			if err != nil {
				warning("seal auth packet failed: %v", err)
				continue
			}
			if err := path.send(b); err != nil {
				warning("send auth packet failed: %v", err)
				continue
			}
			continue
		}

		// Case 3: packet from unknown path.
		// Only valid authentication packets can create a new authed path.
		isAuthPacket, clientID, newSerialNumber, hello := c.proxy.openAuthPacket(buf[:n])
		if !isAuthPacket {
			continue
		}

		client = c.proxy.getClient(clientID)
		if client == nil {
			warning("get client [%x] return nil", clientID)
			continue
		}
		if client.closed.Load() {
			debug("invalid udp packet: client [%x] is closed", clientID)
			continue
		}

		oldSerialNumber := client.serialNumber.Load()
		if newSerialNumber <= oldSerialNumber {
			// Ignore stale authentication packets from unknown paths.
			// They may be delayed requests from an old path, packets from the
			// slower IPv4/IPv6 attempt in a dual-stack race, or replayed packets.
			debug("ignoring stale auth packet from unknown path: client_id=%x, current_serial=%d, received_serial=%d, remote=%s",
				clientID, oldSerialNumber, newSerialNumber, key.remote)
			continue
		}

		if !c.proxy.acceptClientHello(client, hello) {
			continue
		}

		if !client.serialNumber.CompareAndSwap(oldSerialNumber, newSerialNumber) {
			// Calls to readFrom are serialized, so the serial number should not change between the load and CAS.
			warning("unexpected serial change on new path: client_id=%x, expected_serial=%d, received_serial=%d, current_serial=%d, remote=%s",
				clientID, oldSerialNumber, newSerialNumber, client.serialNumber.Load(), key.remote)
			continue
		}

		// Build oob once per accepted path, not per packet.
		path := packet.path
		path.oob = path.socket.replyOOB(path.key.local)

		// Store as authenticated but not yet activated path.
		if !client.setAuthedPath(nil, &path) {
			debug("set authed path failed: client [%x] is closed", clientID)
			continue
		}
		debug("client [%x] [%d] authed from %s", clientID, newSerialNumber, key.remote)

		// Send authentication response (ack).
		b, err := c.proxy.sealAuthPacket(newSerialNumber, hello)
		if err != nil {
			warning("seal auth packet failed: %v", err)
			continue
		}
		if err := path.send(b); err != nil {
			warning("send auth packet failed: %v", err)
			continue
		}
	}
}

func (c *udpFrontendConn) writeTo(buf []byte, client *clientState) error {
	path := client.clientPath.Load()
	if path == nil {
		return errClientDisconnected
	}

	return path.send(buf)
}

type tcpFrameSignal struct {
	conn   *net.TCPConn
	client *clientState
	length int
	ackCh  chan error
}

type tcpFrontendConn struct {
	proxy         *serverProxy
	listenerList  []*net.TCPListener
	frameSignalCh chan tcpFrameSignal
}

func (c *tcpFrontendConn) start(proxy *serverProxy) {
	c.proxy = proxy

	if proxy.args.Attachable {
		c.frameSignalCh = make(chan tcpFrameSignal, 10)
	}

	// Listeners stay open until exit, so clients can reconnect at any time.
	for _, listener := range c.listenerList {
		addOnExitFunc(func() { _ = listener.Close() })
		go c.serve(listener)
	}
}

func (c *tcpFrontendConn) serve(listener *net.TCPListener) {
	defer func() { _ = listener.Close() }()

	warned := false
	for {
		conn, err := listener.AcceptTCP()
		if err != nil {
			if errors.Is(err, net.ErrClosed) {
				return
			}

			var netErr net.Error
			if errors.As(err, &netErr) && netErr.Timeout() {
				continue
			}

			if !warned {
				warning("frontend accept tcp failed: %v", err)
				warned = true
			}
			time.Sleep(10 * time.Millisecond)
			continue
		}

		warned = false

		go c.handshake(conn)
	}
}

func (c *tcpFrontendConn) handshake(conn *net.TCPConn) {
	ok := false
	defer func() {
		if !ok {
			_ = conn.Close()
		}
	}()

	if err := conn.SetReadDeadline(time.Now().Add(c.proxy.args.ConnectTimeout)); err != nil {
		return
	}
	buffer := make([]byte, 128)
	n, err := recvUdpPacket(conn, buffer)
	if err != nil {
		return
	}

	isAuthPacket, clientID, newSerialNumber, hello := c.proxy.openAuthPacket(buffer[:n])
	if !isAuthPacket {
		return
	}

	client := c.proxy.getClient(clientID)
	if client == nil {
		warning("handshake failed: get client [%x] return nil", clientID)
		return
	}
	if client.closed.Load() {
		debug("handshake failed: client [%x] is closed", clientID)
		return
	}

	// Serialize authentication and connection replacement.
	client.tcpAuthMutex.Lock()
	defer client.tcpAuthMutex.Unlock()

	oldSerialNumber := client.serialNumber.Load()

	if newSerialNumber <= oldSerialNumber {
		// Ignore stale authentication packets from unknown paths.
		// They may be delayed requests from an old path, packets from the
		// slower IPv4/IPv6 attempt in a dual-stack race, or replayed packets.
		debug("ignoring stale auth packet from connection: client_id=%x, current_serial=%d, received_serial=%d, remote=%s",
			clientID, oldSerialNumber, newSerialNumber, conn.RemoteAddr())
		return
	}

	if !c.proxy.acceptClientHello(client, hello) {
		return
	}

	if !client.serialNumber.CompareAndSwap(oldSerialNumber, newSerialNumber) {
		// Serialized by tcpAuthMutex, so the serial number should not change between the load and CAS.
		warning("unexpected serial change on tcp path: client_id=%x, expected_serial=%d, received_serial=%d, current_serial=%d, remote=%s",
			clientID, oldSerialNumber, newSerialNumber, client.serialNumber.Load(), conn.RemoteAddr())
		return
	}

	// auth success
	debug("client [%x] [%d] authed from %s", clientID, newSerialNumber, conn.RemoteAddr())
	if b, err := c.proxy.sealAuthPacket(newSerialNumber, hello); err != nil {
		warning("seal auth packet failed: %v", err)
		return
	} else if err := sendUdpPacket(conn, b); err != nil {
		warning("send auth packet failed: %v", err)
		return
	}

	setDSCP(conn, kProxyDSCP)
	_ = conn.SetReadDeadline(time.Time{})
	_ = conn.SetReadBuffer(kProxyBufferSize)
	_ = conn.SetWriteBuffer(kProxyBufferSize)

	if !client.setClientConn(nil, conn) {
		debug("set client conn failed: client [%x] is closed", clientID)
		return
	}

	c.proxy.onNewClientConn(client)
	ok = true

	if c.proxy.args.Attachable {
		go c.readLoop(conn, client)
	}
}

func (c *tcpFrontendConn) readLoop(conn *net.TCPConn, client *clientState) {
	buf := make([]byte, 2)
	ackCh := make(chan error)

	defer client.setClientConn(conn, nil)

	for conn == client.clientConn.Load() {

		if _, err := io.ReadFull(conn, buf); err != nil {
			return
		}

		c.frameSignalCh <- tcpFrameSignal{
			conn:   conn,
			client: client,
			length: int(binary.BigEndian.Uint16(buf)),
			ackCh:  ackCh,
		}

		if err := <-ackCh; err != nil {
			return
		}
	}
}

func (c *tcpFrontendConn) readFrom(buf []byte) (int, *clientState) {
	if c.proxy.args.Attachable {
		for {
			signal := <-c.frameSignalCh

			if len(buf) < int(signal.length) {
				warning("read buffer too short: buffer=%d, decoded frame length=%d", len(buf), signal.length)
				signal.ackCh <- io.ErrShortBuffer
				continue
			}

			n, err := io.ReadFull(signal.conn, buf[:signal.length])
			if err != nil {
				signal.ackCh <- err
				continue
			}

			signal.ackCh <- nil
			return n, signal.client
		}
	}

	client := c.proxy.soleClient
	for {
		conn := client.waitClientConn()
		if conn == nil {
			return 0, nil
		}

		n, err := recvUdpPacket(conn, buf)
		if err != nil {
			client.setClientConn(conn, nil)
			continue
		}

		return n, client
	}
}

func (c *tcpFrontendConn) writeTo(buf []byte, client *clientState) error {
	conn := client.clientConn.Load()
	if conn == nil {
		return errClientDisconnected
	}

	if err := sendUdpPacket(conn, buf); err != nil {
		client.setClientConn(conn, nil)
		return err
	}

	return nil
}

func (c *tcpFrontendConn) addClientMap(*clientState) {}

func (c *tcpFrontendConn) delClientMap(*clientState, *udpPath) {}

func (c *tcpFrontendConn) addAuthedMap(*clientState) {}

func (c *tcpFrontendConn) delAuthedMap(*clientState, *udpPath) {}

func (c *tcpFrontendConn) Close() {
	for _, listener := range c.listenerList {
		_ = listener.Close()
	}
}

type serverProxy struct {
	args         *tsshdArgs
	readMutex    sync.Mutex
	frontendConn frontendConnection
	cipherBlock  *cipher.Block
	serverID     uint64
	clientID     uint64
	soleClient   *clientState
	clientMutex  sync.RWMutex
	kcpCrypto    *rotatingCrypto
	// This map is intentionally not cleaned up to prevent replay attacks.
	// Only optimize if memory usage becomes a real issue, and even then,
	// serialNumber must be retained for replay protection.
	clientMap map[uint64]*clientState
}

func (p *serverProxy) newClientState(clientID uint64) (*clientState, error) {
	client := &clientState{proxyAddr: proxyClientAddr{clientID}, frontendConn: p.frontendConn}

	if p.args.TCP {
		client.clientCond = sync.NewCond(&client.clientMutex)
	}

	if p.args.KCP && p.args.Attachable {
		client.kcpCrypto.Store(newServerCrypto(p.kcpCrypto.keyPass, p.kcpCrypto.keySalt, false))
	}

	client.udpTraffic.Store(&trafficStats{})

	return client, nil
}

func (p *serverProxy) getClient(clientID uint64) *clientState {
	if !p.args.Attachable && clientID == p.clientID {
		return p.soleClient
	}

	p.clientMutex.RLock()
	client, ok := p.clientMap[clientID]
	p.clientMutex.RUnlock()
	if ok {
		return client
	}

	p.clientMutex.Lock()
	defer p.clientMutex.Unlock()

	if client, ok = p.clientMap[clientID]; ok {
		return client
	}

	client, err := p.newClientState(clientID)
	if err != nil {
		warning("new client state failed: %v", err)
		return nil
	}

	if p.clientMap == nil {
		p.clientMap = make(map[uint64]*clientState)
	}
	p.clientMap[clientID] = client

	return client
}

// sealAuthPacket acknowledges the authentication packet that carried hello.
// The client nonce is echoed, so that the client can tell that the
// acknowledgment is meant for it, and not for an earlier client.
func (p *serverProxy) sealAuthPacket(serialNumber uint64, hello *clientHello) ([]byte, error) {
	data := make([]byte, 16, 16+kClientNonceSize)
	binary.BigEndian.PutUint64(data[0:8], p.serverID)
	binary.BigEndian.PutUint64(data[8:16], serialNumber)
	data = append(data, hello.clientNonce...)
	buf := aesEncrypt(p.cipherBlock, data)
	if buf == nil {
		return nil, errors.New("aes encrypt failed")
	}
	return buf, nil
}

// openAuthPacket returns the client ID, the serial number, and what the
// client announced about itself.
func (p *serverProxy) openAuthPacket(buf []byte) (bool, uint64, uint64, *clientHello) {
	data := aesDecrypt(p.cipherBlock, buf)
	if len(data) != 16 && len(data) != 20+kClientNonceSize {
		return false, 0, 0, nil
	}

	// Reserve the server ID so a legacy acknowledgment cannot authenticate a client.
	clientID := binary.BigEndian.Uint64(data[0:8])
	if clientID == p.serverID || (!p.args.Attachable && clientID != p.clientID) {
		return false, 0, 0, nil
	}

	serialNumber := binary.BigEndian.Uint64(data[8:16])

	hello := &clientHello{}
	if len(data) > 16 {
		hello.protoVersion = int(min(binary.BigEndian.Uint32(data[16:20]), kTsshdProtocol))
		hello.clientNonce = data[20:]
	}

	return true, clientID, serialNumber, hello
}

// acceptClientHello reports whether the authentication packet carrying hello
// comes from the client that authenticated first. A client never changes what
// it announces, so anything else belongs to another client started with the
// same server info, which must not take over the connection.
//
// The first authentication installs the KCP traffic key of the client.
func (p *serverProxy) acceptClientHello(client *clientState, hello *clientHello) bool {
	client.helloMutex.Lock()
	defer client.helloMutex.Unlock()

	if client.hello != nil {
		if client.hello.protoVersion != hello.protoVersion ||
			!bytes.Equal(client.hello.clientNonce, hello.clientNonce) {
			debug("authenticate rejected: client [%x] has been replaced", client.proxyAddr.clientID)
			return false
		}
		return true
	}

	kcpCrypto := p.kcpCrypto
	if p.args.Attachable {
		kcpCrypto = client.kcpCrypto.Load()
	}
	if kcpCrypto != nil {
		if err := kcpCrypto.setClientHello(hello.protoVersion, client.proxyAddr.clientID, hello.clientNonce); err != nil {
			warning("install traffic key for client [%x] failed: %v", client.proxyAddr.clientID, err)
			return false
		}
	}

	client.hello = hello
	return true
}

func (p *serverProxy) onNewClientConn(client *clientState) {
	client.clientMutex.Lock()
	defer client.clientMutex.Unlock()

	if client.closed.Load() {
		return
	}

	if enableDebugLogging.Load() {
		debug("client [%x] [%d] active from %s", client.proxyAddr.clientID, client.serialNumber.Load(), client.remoteAddr())
	}

	if server := client.server.Load(); server != nil {
		// Discard pending terminal input from previous sessions to prevent stale
		// or unintended input (possibly generated while the client was disconnected)
		// from being delivered after reconnection.
		server.enablePendingInputDiscard()

		server.proto.reset()
	}
}

func (p *serverProxy) updateClientChecker(client *clientState) {
	if server := client.server.Load(); server != nil {
		server.clientChecker.updateNow()
	}
}

func (p *serverProxy) ReadFrom(buf []byte) (int, net.Addr, error) {
	p.readMutex.Lock()
	defer p.readMutex.Unlock()

	var n int
	var client *clientState

	for {
		n, client = p.frontendConn.readFrom(buf)

		if client == nil {
			return 0, nil, io.EOF
		}

		if kcpCrypto := client.kcpCrypto.Load(); kcpCrypto != nil {
			nn, err := kcpCrypto.openPacket(buf[:n])
			if err != nil {
				debug("open packet (len=%d) failed: %v", n, err)
				continue
			}
			n = nn
		}

		// For attachable clients, Close sets closed before clearing kcpCrypto.
		// Load the key first, then discard the packet if the client was closed.
		if client.closed.Load() {
			continue
		}

		break
	}

	// Without the per-client crypto above, the packet has not been opened yet.
	// The KCP listener is about to do so, and refreshes the checker itself.
	if !p.args.KCP || p.args.Attachable {
		p.updateClientChecker(client)
	}

	if enableDebugLogging.Load() {
		if traffic := client.udpTraffic.Load(); traffic != nil && traffic.recFlag.Load() {
			traffic.recvCount.Add(1)
			traffic.recvBytes.Add(uint64(n))
		}
	}

	return n, &client.proxyAddr, nil
}

// Do not return an error here, otherwise QUIC/KCP may drop all subsequent packets.
func (p *serverProxy) WriteTo(buf []byte, addr net.Addr) (int, error) {
	n := len(buf)
	clientAddr, ok := addr.(*proxyClientAddr)
	if !ok {
		warning("server proxy write to invalid addr type: %T", addr)
		return n, nil
	}

	client := p.getClient(clientAddr.clientID)
	if client == nil {
		warning("get client [%x] return nil", clientAddr.clientID)
		return n, nil
	}

	if kcpCrypto := client.kcpCrypto.Load(); kcpCrypto != nil {
		var err error
		buf, err = kcpCrypto.sealPacket(buf, true)
		if err != nil {
			warning("seal packet failed: %v", err)
			return n, nil
		}
	}

	// If kcpCrypto is cleared, 'closed' is guaranteed to be true.
	// Checking 'closed' after fetching kcpCrypto avoids a race condition that leaks plaintext data.
	if client.closed.Load() {
		debug("skip write: client [%x] is closed", clientAddr.clientID)
		return n, nil
	}

	if err := p.frontendConn.writeTo(buf, client); err != nil {
		if err != errClientDisconnected {
			debug("frontend write failed: %v", err)
		}
	} else if enableDebugLogging.Load() {
		if traffic := client.udpTraffic.Load(); traffic != nil && traffic.recFlag.Load() {
			traffic.sendCount.Add(1)
			traffic.sendBytes.Add(uint64(len(buf)))
		}
	}

	return n, nil
}

